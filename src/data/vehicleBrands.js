// Helper function to get brands for a vehicle category
export const getBrandsForCategory = (category) => {
  switch (category) {
    case 'car':
      return carBrands;
    case 'bike':
    case 'motorcycle':
      return bikeBrands;
    case 'boat':
      return boatBrands;
    case 'aircraft':
      return aircraftBrands;
    case 'uav':
    case 'uavs':
      return uavBrands;
    default:
      return carBrands;
  }
};

// Helper function to get brand names as array
export const getBrandNames = (category) => {
  const brands = getBrandsForCategory(category);
  return Object.keys(brands).sort();
};

// Helper function to get models for a specific brand
export const getModelsForBrand = (category, brand) => {
  const brands = getBrandsForCategory(category);
  return brands[brand] || [];
};
